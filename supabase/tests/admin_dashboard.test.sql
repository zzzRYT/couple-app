begin;
select plan(17);
grant admin_dashboard_reader to postgres;
grant usage on schema extensions to admin_dashboard_reader; -- pgTAP helpers in this transaction only
select ok(not has_function_privilege('anon','public.admin_dashboard()','execute'),'anon cannot execute');
select ok(not has_function_privilege('authenticated','public.admin_dashboard()','execute'),'authenticated cannot execute');
select ok(has_function_privilege('admin_dashboard_reader','public.admin_dashboard()','execute'),'reader can execute');
select ok(not has_function_privilege('service_role','public.admin_dashboard()','execute'),'service role has no implicit aggregate grant');
select ok(not exists (select 1 from pg_proc p join pg_namespace n on n.oid=p.pronamespace where n.nspname='public' and p.oid <> 'public.admin_dashboard()'::regprocedure and has_function_privilege('admin_dashboard_reader',p.oid,'execute')),'reader cannot execute other public functions');
select ok(not exists (select 1 from pg_class c join pg_namespace n on n.oid=c.relnamespace where n.nspname='public' and c.relkind in ('r','p','v','m') and (has_table_privilege('admin_dashboard_reader',c.oid,'select,insert,update,delete') or has_any_column_privilege('admin_dashboard_reader',c.oid,'select,insert,update'))),'reader has no table or column access');
set local role anon;
select throws_ok('select public.admin_dashboard()', '42501', null, 'anon call denied');
reset role;
set local role authenticated;
select throws_ok('select public.admin_dashboard()', '42501', null, 'authenticated call denied');
reset role;
set local role admin_dashboard_reader;
select lives_ok('select public.admin_dashboard()', 'reader can run fixed aggregate');
select throws_ok('select * from public.user_profile', '42501', null, 'reader cannot read raw profiles');
select throws_ok($$insert into public.couple_space (anniversary_date) values ('2025-01-01')$$, '42501', null, 'reader cannot write');
reset role;
-- Isolate all six aggregates within this rollback-only local transaction.
set local session_replication_role = replica;
delete from public.user_profile;
delete from public.couple_space;
delete from public.space_anniversary;
delete from public.report;
delete from public.report_fingerprint;
delete from public.account_deletion;
insert into public.user_profile(user_id) values ('00000000-0000-0000-0000-0000000000d1');
insert into public.couple_space(id,anniversary_date) values ('10000000-0000-0000-0000-0000000000d1','2025-01-01');
insert into public.space_anniversary(space_id,title,event_date,repeat) values ('10000000-0000-0000-0000-0000000000d1','fixture','2025-01-01','once');
insert into public.report(space_id,reporter_user_id,target,reason) values ('10000000-0000-0000-0000-0000000000d1','00000000-0000-0000-0000-0000000000d1','partner','other');
insert into public.report_fingerprint(target,reason,reported_at) select 'partner','other',now() from generate_series(1,5);
insert into public.report_fingerprint(target,reason,reported_at) values ('partner','privacy',now());
insert into public.account_deletion(user_id,provider) values ('00000000-0000-0000-0000-0000000000d1','email');
set local role admin_dashboard_reader;
select ok((select bool_and(public.admin_dashboard()->key='null'::jsonb) from unnest(array['active_profiles','active_anniversaries','spaces','reports','fingerprints','deletions']) as key),'all small counts and complementary cells are suppressed');
reset role;
delete from public.report_fingerprint where reason='privacy';
set local role admin_dashboard_reader;
select is((public.admin_dashboard()->'fingerprints'->0->>'count')::integer,5,'count of five shown');
reset role;
delete from public.report_fingerprint;
set local role admin_dashboard_reader;
select is(public.admin_dashboard()->'fingerprints','null'::jsonb,'empty breakdown suppressed');
select ok(not has_database_privilege(current_user,current_database(),'create'),'reader cannot create schemas');
select ok(not has_schema_privilege(current_user,'public','create'),'reader cannot create tables or functions');
select ok(not has_table_privilege(current_user,'public.report','select'),'reader cannot read reports');
reset role;
select * from finish();
rollback;
