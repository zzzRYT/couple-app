import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('../../', import.meta.url));
const dir = `${root}apps/mobile/src/i18n/locales/v0`;
const source = readFileSync(`${dir}/copy-v0.md`, 'utf8');
const check = process.argv.includes('--check');
function output(path, content) {
  if (check) {
    if (readFileSync(path, 'utf8') !== content) throw new Error(`Stale V0 overlay: ${path}; run node tools/i18n/build-v0-overlay.mjs`);
  } else writeFileSync(path, content);
}
if (check && source !== readFileSync(`${root}specs/002-couple-dday-v0/handoffs/design/copy-v0.md`, 'utf8')) throw new Error('V0 overlay copy differs from the H02 design extract');
const locales = [{}, {}, {}];
const seen = new Set();
for (const line of source.split('\n')) {
  if (!/^\| `[^`]+` \|/.test(line)) continue;
  const cells = line.replace(/\\\|/g, '\u0000').split('|').slice(1, -1).map((s) => s.trim().replace(/\u0000/g, '|').replace(/⏎/g, '\n'));
  const key = cells[0].slice(1, -1);
  if (seen.has(key)) throw new Error(`duplicate key: ${key}`);
  seen.add(key);
  for (let i = 0; i < 3; i++) {
    let value = cells[i + 1].replace(/모피루|Mopiru|モピル/g, '$t(app.name)').replace(/모피|Mopi|モピ/g, '$t(mascot.name)');
    if (i === 0) value = value.replace(/\$t\(app\.name\)(를|가|는|와|로)/g, (_, particle) => `$t(app.name)${({ 를: '을', 가: '이', 는: '은', 와: '과', 로: '으로' })[particle]}`);
    locales[i][key] = value;
  }
}
if (seen.size !== 278) throw new Error(`expected 278 rows, got ${seen.size}`);
for (const [i, name] of ['ko-KR', 'en-US', 'ja-JP'].entries()) {
  locales[i]['app.name'] = ['아룸', 'Aroom', 'アルーム'][i];
  locales[i]['mascot.name'] = ['아루미', 'Aroomi', 'アルーミ'][i];
  output(`${dir}/${name}.json`, `${JSON.stringify(locales[i], null, 2)}\n`);
}
output(`${root}apps/mobile/src/i18n/v0Keys.d.ts`, `// Generated by tools/i18n/build-v0-overlay.mjs.\nexport type V0Key =\n${Object.keys(locales[0]).map((key) => `  | ${JSON.stringify(key)}`).join('\n')};\n`);
