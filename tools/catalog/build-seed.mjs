import { readFile, writeFile } from 'node:fs/promises';
const entries = JSON.parse(await readFile('assets/catalog/manifest.json', 'utf8'));
const q = (value) => value === null || value === undefined ? 'null' : typeof value === 'number' ? String(value) : `'${String(value).replaceAll("'", "''")}'`;
const columns = ['asset_id', 'catalog_version', 'asset_kind', 'uri', 'format', 'width_px', 'height_px', 'byte_size', 'sha256', 'license_kind', 'rights_record_ref', 'status'];
const rows = entries.map((e) => `  (${columns.map((c) => q(e[c])).join(', ')})`);
await writeFile('supabase/seed/catalog.sql', `-- Generated by tools/catalog/build-seed.mjs from assets/catalog/manifest.json; do not edit.
insert into public.asset_catalog_entry (${columns.join(', ')}) values
${rows.join(',\n')}
on conflict (asset_id) do update set ${columns.slice(1).map((c) => `${c}=excluded.${c}`).join(', ')};
`);
